let stationData = null;
let selectedPreference = "wheelchair";
let currentLanguage = "en";

const $ = (id) => document.getElementById(id);
const t = (key) => translations[currentLanguage][key] || translations.en[key] || key;

async function loadStation() {
  try {
    const response = await fetch("/api/station");
    if (!response.ok) throw new Error("Could not load station data.");
    stationData = await response.json();
    const start = $("start"), end = $("end");
    start.innerHTML = ""; end.innerHTML = "";
    stationData.nodes.forEach(node => {
      const a = new Option(node.name, node.id);
      const b = new Option(node.name, node.id);
      start.add(a); end.add(b);
    });
    start.value = "gate_a";
    end.value = "platform_1";
  } catch (error) {
    $("form-message").textContent = error.message;
  }
}

function applyLanguage() {
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[currentLanguage][key]) el.textContent = t(key);
  });
  if (stationData) {
    const startValue = $("start").value, endValue = $("end").value;
    $("start").innerHTML = ""; $("end").innerHTML = "";
    stationData.nodes.forEach(node => {
      $("start").add(new Option(node.name, node.id));
      $("end").add(new Option(node.name, node.id));
    });
    $("start").value = startValue; $("end").value = endValue;
  }
}

function edgeLabel(type) {
  return ({walk:t("walk"), lift:t("lift"), stairs:t("stairsType"), escalator:t("escalator")})[type] || type;
}

function renderRoute(route) {
  $("results").hidden = false;
  $("route-title").textContent = t("routeFound");
  $("route-time").textContent = route.total_minutes;
  $("route-summary").textContent = `${route.nodes[0].name} → ${route.nodes[route.nodes.length - 1].name}`;
  const list = $("route-list");
  list.innerHTML = "";
  route.nodes.forEach((node, index) => {
    const item = document.createElement("li");
    const dot = document.createElement("span");
    dot.className = "route-dot";
    dot.textContent = index === 0 ? "●" : index === route.nodes.length - 1 ? "◎" : "•";
    const text = document.createElement("span");
    text.className = "route-step";
    const strong = document.createElement("strong");
    strong.textContent = node.name;
    const small = document.createElement("small");
    small.textContent = node.description;
    text.append(strong, small);
    const time = document.createElement("span");
    time.className = "edge-time";
    if (index > 0) time.textContent = `${edgeLabel(route.edges[index - 1].type)} · ${route.edges[index - 1].minutes} min`;
    item.append(dot, text, time);
    list.append(item);
  });
  $("results").scrollIntoView({behavior:"smooth", block:"nearest"});
}

async function findRoute() {
  $("form-message").textContent = "";
  const start = $("start").value, end = $("end").value;
  if (!start || !end) {
    $("form-message").textContent = t("errors");
    return;
  }
  const button = $("find-route");
  button.disabled = true;
  button.querySelector("span").textContent = "Finding…";
  try {
    const response = await fetch("/api/route", {
      method:"POST",
      headers:{"Content-Type":"application/json"},
      body:JSON.stringify({start, end, preference:selectedPreference})
    });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error || "Unable to calculate route.");
    renderRoute(result);
  } catch (error) {
    $("results").hidden = true;
    $("form-message").textContent = error.message;
  } finally {
    button.disabled = false;
    button.querySelector("span").textContent = t("find");
  }
}

document.querySelectorAll(".preference").forEach(button => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".preference").forEach(item => item.classList.remove("selected"));
    button.classList.add("selected");
    selectedPreference = button.dataset.preference;
  });
});
$("find-route").addEventListener("click", findRoute);
$("language").addEventListener("change", event => {
  currentLanguage = event.target.value;
  applyLanguage();
});
$("swap").addEventListener("click", () => {
  const oldStart = $("start").value;
  $("start").value = $("end").value;
  $("end").value = oldStart;
});
loadStation();
